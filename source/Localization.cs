    private static readonly string SystemLanguage = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
    public static CultureInfo Culture { get; private set; } = CultureInfo.GetCultureInfo("en-US");
    public static bool Russian => Culture.TwoLetterISOLanguageName == "ru";

    public static void SetLanguage(string? language)
    {
        string selected = language switch { "ru" => "ru", "en" => "en", _ => SystemLanguage };
        Culture = CultureInfo.GetCultureInfo(selected == "ru" ? "ru-RU" : "en-US");
    }

    // Для проверки перевода: в русском режиме запоминает английские строки, для которых нет перевода (включается только в --audit-ui)
    internal static bool TrackMissing { get; set; }
    internal static readonly SortedSet<string> Missing = new(StringComparer.Ordinal);

    public static string T(string value)
    {
        if (!Russian || value.Length == 0) return value;
        string key = value.Trim();
        if (!RussianText.TryGetValue(key, out var translated))
        {
            if (TrackMissing && key.Any(char.IsAsciiLetter) && !key.Any(character => character is >= 'Ѐ' and <= 'ӿ')) Missing.Add(key);
            return value;
        }
        int start = value.IndexOf(key, StringComparison.Ordinal);
        return value[..start] + translated + value[(start + key.Length)..];
    }

    public static string Pair(string english, string russian) => Russian ? russian : english;

    public static string Condition(string value) => value == "Clear" ? Pair(value, "Ясно") : T(value);

    public static bool Matches(string value, string term) =>
        value.Contains(term, StringComparison.OrdinalIgnoreCase)
        || Culture.CompareInfo.IndexOf(T(value), term, CompareOptions.IgnoreCase) >= 0;

    public static string Metric(string value)
    {
        if (!Russian) return value;
        string simple = T(value);
        if (simple != value) return simple;
        foreach (var (pattern, template, metricName) in Metrics)
            if (pattern.Match(value) is { Success: true } match)
            {
                var values = match.Groups.Cast<Group>().Skip(1)
                    .Select((group, index) => (object)(metricName && index == 1 ? T(group.Value) : group.Value)).ToArray();
                return string.Format(Culture, template, values);
            }
        return value;
    }

    private static readonly (Regex Pattern, string Text, bool MetricName)[] Metrics =
    [
        MetricRule("(\\d+(?:[.,\\s]\\d+)*) (events|repos|followers|solved|unread|clicks|open|projects|visitors|subscribers|currencies)",
            "{1}: {0}", true),
        MetricRule("(\\d+/\\d+) revenue providers · last 30 days", "Источников: {0} · за последние 30 дней"),
        MetricRule("(.+) · last (\\d+) days", "{0} · за последние {1} дн."),
        MetricRule("(.+) · 24h", "{0} · 24 ч"),
        MetricRule("Delivered · latest (\\d+) messages", "Доставлено · последних сообщений: {0}"),
        MetricRule("([0-9., ]+) easy · ([0-9., ]+) medium · ([0-9., ]+) hard", "Лёгкие: {0} · Средние: {1} · Сложные: {2}")
    ];

    private static (Regex, string, bool) MetricRule(string pattern, string template, bool metricName = false) =>
        (new Regex("\\A" + pattern + "\\z", RegexOptions.CultureInvariant | RegexOptions.NonBacktracking), template, metricName);

    public static string F(FormattableString value)
    {
        string format = Russian && RussianText.TryGetValue(value.Format, out var translation) ? translation : value.Format;
        if (TrackMissing && Russian && format == value.Format && value.Format.Any(char.IsAsciiLetter)) Missing.Add(value.Format);
        return string.Format(Culture, format, value.GetArguments());
    }

